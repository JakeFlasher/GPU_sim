#!/usr/bin/env python3
"""Generate the portable-LCD preserved-binary authorities.

The authority is a projection of the SHA-pinned frozen v1 capture roster.  It
never hashes local binary files.  Source attribution comes from the complete
baseline-to-active-tree Git delta, not from the unrelated SimBench witness
registry.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import subprocess
import sys
import tempfile
from collections import defaultdict
from pathlib import Path
from typing import Any

_IMPORT_ROOT = Path(__file__).resolve().parents[2]
if str(_IMPORT_ROOT) not in sys.path:
    sys.path.insert(0, str(_IMPORT_ROOT))

from tools.local_labels.protected_paths import (
    ProtectedPathError,
    assert_external_output,
    assert_write_allowed,
    discover_repo_root,
)


SOURCE_AUTHORITY_REL = Path(
    "data/local_labels/campaign/capture_roster_authority_sm86.json"
)
SOURCE_AUTHORITY_SHA256 = (
    "d02c817091b0a9f06c2106c0987c59a481910afcc3b78ab1de7a7d5bd5a6b4b4"
)
SOURCE_BASELINE_COMMIT = "c4b76c0ae3b49378f6e3d4cabf7830dbe3eaa432"
PORTABLE_ROOT_REL = Path("workloads/portable_lcd")
MANIFEST_REL = PORTABLE_ROOT_REL / "preserved_binaries_manifest.json"
MARKDOWN_REL = PORTABLE_ROOT_REL / "PRESERVED_BINARIES.md"

REQUIRED_NON_GENERATED_DELTA = frozenset(
    {
        "workloads/portable_lcd/README.md",
        "workloads/portable_lcd/runner_common.h",
        "workloads/portable_lcd/ac4_mixed_long_sm80/ac4_mixed_long_sm80.cu",
        "workloads/portable_lcd/ac4_mixed_long_sm80/PRESERVED_BINARY.md",
        "workloads/portable_lcd/conv2d_implicit_gemm_bf16_sm80/main.cu",
        "workloads/portable_lcd/gemm_hmma_bf16_sm80/main.cu",
    }
)
GENERATED_DELTA = frozenset({MANIFEST_REL.as_posix(), MARKDOWN_REL.as_posix()})

_PREAMBLE = """# Preserved portable LCD binaries

> Generated by `tools/local_labels/build_preserved_binaries.py`; do not edit.

Source authority: `data/local_labels/campaign/capture_roster_authority_sm86.json`
Source authority SHA-256: `d02c817091b0a9f06c2106c0987c59a481910afcc3b78ab1de7a7d5bd5a6b4b4`
Source baseline commit: `c4b76c0ae3b49378f6e3d4cabf7830dbe3eaa432`
Preserved binaries: 15 (ac4 excluded; separately protected)

| Binary path | SHA-256 | Cells | Diverged sources |
| --- | --- | --- | --- |
"""


class PreservationPrerequisiteError(RuntimeError):
    """A repository, authority, commit, or required input is absent."""


class PreservationValidationError(RuntimeError):
    """Present preservation inputs violate the closed contract."""


def _git(repo_root: Path, *args: str) -> subprocess.CompletedProcess[bytes]:
    try:
        return subprocess.run(
            ["git", "-C", str(repo_root), *args],
            check=False,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
        )
    except OSError as exc:
        raise PreservationPrerequisiteError(f"cannot execute Git: {exc}") from exc


def _safe_repo_relative(value: object, *, field: str) -> str:
    if not isinstance(value, str) or not value:
        raise PreservationValidationError(f"{field} must be a nonempty string")
    parts = value.split("/")
    if (
        value.startswith("/")
        or "\\" in value
        or any(part in ("", ".", "..") for part in parts)
        or any(ord(character) < 0x20 or ord(character) == 0x7F for character in value)
    ):
        raise PreservationValidationError(f"{field} is not a safe repository path: {value!r}")
    return value


def _load_authority(repo_root: Path) -> dict[str, Any]:
    path = repo_root / SOURCE_AUTHORITY_REL
    try:
        payload = path.read_bytes()
    except OSError as exc:
        raise PreservationPrerequisiteError(f"source authority is unreadable: {path}: {exc}") from exc
    actual = hashlib.sha256(payload).hexdigest()
    if actual != SOURCE_AUTHORITY_SHA256:
        raise PreservationValidationError(
            f"source authority SHA-256 mismatch: expected={SOURCE_AUTHORITY_SHA256} "
            f"actual={actual} path={path}"
        )
    try:
        value = json.loads(payload)
    except json.JSONDecodeError as exc:
        raise PreservationValidationError(f"source authority JSON is invalid: {exc}") from exc
    if not isinstance(value, dict) or not isinstance(value.get("cells"), list):
        raise PreservationValidationError("source authority must be an object with cells array")
    return value


def _portable_delta(repo_root: Path) -> set[str]:
    if _git(repo_root, "cat-file", "-e", f"{SOURCE_BASELINE_COMMIT}^{{commit}}").returncode:
        raise PreservationPrerequisiteError(
            f"source baseline commit is unavailable: {SOURCE_BASELINE_COMMIT}"
        )
    changed = _git(
        repo_root,
        "diff",
        "--name-only",
        "--no-renames",
        SOURCE_BASELINE_COMMIT,
        "--",
        PORTABLE_ROOT_REL.as_posix(),
    )
    if changed.returncode:
        raise PreservationPrerequisiteError(
            f"cannot derive portable delta: {changed.stderr.decode(errors='replace').strip()}"
        )
    untracked = _git(
        repo_root,
        "ls-files",
        "--others",
        "--exclude-standard",
        "--",
        PORTABLE_ROOT_REL.as_posix(),
    )
    if untracked.returncode:
        raise PreservationPrerequisiteError(
            f"cannot derive untracked portable delta: "
            f"{untracked.stderr.decode(errors='replace').strip()}"
        )
    result = set(changed.stdout.decode().splitlines())
    result.update(untracked.stdout.decode().splitlines())
    return result


def _validate_delta(repo_root: Path) -> None:
    observed = _portable_delta(repo_root)
    non_generated = observed - GENERATED_DELTA
    if non_generated != REQUIRED_NON_GENERATED_DELTA:
        missing = sorted(REQUIRED_NON_GENERATED_DELTA - non_generated)
        extra = sorted(non_generated - REQUIRED_NON_GENERATED_DELTA)
        raise PreservationValidationError(
            f"portable source delta is not the closed C1 set: missing={missing} extra={extra}"
        )
    generated_extra = observed & GENERATED_DELTA
    if generated_extra - GENERATED_DELTA:
        raise PreservationValidationError(
            f"unexpected generated portable delta: {sorted(generated_extra - GENERATED_DELTA)}"
        )


def _derive_rows(authority: dict[str, Any]) -> list[dict[str, Any]]:
    portable = [
        cell
        for cell in authority["cells"]
        if isinstance(cell, dict)
        and cell.get("roster_source") == "portable_lcd"
        and cell.get("resolution_status") == "runnable"
    ]
    if len(portable) != 17:
        raise PreservationValidationError(
            f"expected 17 runnable portable cells, found {len(portable)}"
        )

    grouped: dict[str, list[str]] = defaultdict(list)
    pins: dict[str, str] = {}
    for index, cell in enumerate(portable):
        binary = _safe_repo_relative(cell.get("binary"), field=f"cells[{index}].binary")
        slug = cell.get("slug")
        digest = cell.get("binary_sha256")
        if not isinstance(slug, str) or not slug:
            raise PreservationValidationError(f"cells[{index}].slug is invalid")
        if not isinstance(digest, str) or len(digest) != 64 or any(
            char not in "0123456789abcdef" for char in digest
        ):
            raise PreservationValidationError(f"cells[{index}].binary_sha256 is invalid")
        if binary in pins and pins[binary] != digest:
            raise PreservationValidationError(f"binary pin disagreement for {binary}")
        pins[binary] = digest
        grouped[binary].append(slug)

    if len(grouped) != 16:
        raise PreservationValidationError(
            f"expected 16 unique portable binaries, found {len(grouped)}"
        )
    ac4 = [path for path in grouped if "/ac4_mixed_long_sm80/" in path]
    if len(ac4) != 1 or len(grouped[ac4[0]]) != 2:
        raise PreservationValidationError(
            f"expected one two-cell ac4 binary, found {[(p, grouped[p]) for p in ac4]}"
        )

    rows: list[dict[str, Any]] = []
    for binary in sorted(set(grouped) - set(ac4)):
        sources = ["workloads/portable_lcd/runner_common.h"]
        if "/conv2d_implicit_gemm_bf16_sm80/" in binary:
            sources.append(
                "workloads/portable_lcd/conv2d_implicit_gemm_bf16_sm80/main.cu"
            )
        if "/gemm_hmma_bf16_sm80/" in binary:
            sources.append("workloads/portable_lcd/gemm_hmma_bf16_sm80/main.cu")
        rows.append(
            {
                "binary_path": binary,
                "binary_sha256": pins[binary],
                "cells": sorted(grouped[binary]),
                "diverged_sources": sorted(sources),
            }
        )
    if len(rows) != 15:
        raise PreservationValidationError(
            f"expected 15 preserved manifest rows, found {len(rows)}"
        )
    return rows


def build_output_bytes(*, repo_root: Path | str | None = None) -> tuple[bytes, bytes]:
    """Return canonical JSON and Markdown without reading local binaries."""

    root = (
        Path(repo_root).resolve(strict=True)
        if repo_root is not None
        else discover_repo_root(Path(__file__))
    )
    _validate_delta(root)
    authority = _load_authority(root)
    rows = _derive_rows(authority)
    manifest = {
        "schema_version": 1,
        "source_authority": {
            "path": SOURCE_AUTHORITY_REL.as_posix(),
            "sha256": SOURCE_AUTHORITY_SHA256,
        },
        "source_baseline_commit": SOURCE_BASELINE_COMMIT,
        "binaries": rows,
    }
    manifest_bytes = (
        json.dumps(manifest, ensure_ascii=True, sort_keys=True, indent=2) + "\n"
    ).encode("utf-8")

    lines = [_PREAMBLE]
    for row in rows:
        cells = "<br>".join(f"`{item}`" for item in row["cells"])
        sources = "<br>".join(f"`{item}`" for item in row["diverged_sources"])
        lines.append(
            f"| `{row['binary_path']}` | `{row['binary_sha256']}` | "
            f"{cells} | {sources} |\n"
        )
    markdown_bytes = "".join(lines).encode("utf-8")
    return manifest_bytes, markdown_bytes


def _is_linked_detached_worktree(repo_root: Path) -> bool:
    git_dir = _git(repo_root, "rev-parse", "--absolute-git-dir")
    common = _git(repo_root, "rev-parse", "--path-format=absolute", "--git-common-dir")
    detached = _git(repo_root, "symbolic-ref", "-q", "HEAD")
    worktree_matches_index = _git(repo_root, "diff", "--quiet")
    index_differs_from_head = _git(repo_root, "diff", "--cached", "--quiet")
    if git_dir.returncode or common.returncode:
        return False
    return (
        Path(git_dir.stdout.decode().strip()).resolve(strict=False)
        != Path(common.stdout.decode().strip()).resolve(strict=False)
        and detached.returncode != 0
        and worktree_matches_index.returncode == 0
        and index_differs_from_head.returncode == 1
    )


def _prepare_destination(path: Path) -> None:
    if path.exists() and (path.is_symlink() or not path.is_file()):
        raise PreservationValidationError(
            f"output destination exists but is not a regular file: {path}"
        )
    if path.is_symlink():
        raise PreservationValidationError(f"output destination is a symlink: {path}")
    if not path.parent.is_dir():
        raise PreservationPrerequisiteError(
            f"output parent directory is missing: {path.parent}"
        )


def _atomic_materialize(outputs: tuple[tuple[Path, bytes], ...]) -> None:
    for destination, _payload in outputs:
        _prepare_destination(destination)
    temporaries: list[tuple[Path, Path]] = []
    try:
        for destination, payload in outputs:
            descriptor, raw_temp = tempfile.mkstemp(
                prefix=f".{destination.name}.", suffix=".tmp", dir=destination.parent
            )
            temp_path = Path(raw_temp)
            with os.fdopen(descriptor, "wb") as stream:
                stream.write(payload)
                stream.flush()
                os.fsync(stream.fileno())
            temporaries.append((temp_path, destination))
        for temp_path, destination in temporaries:
            os.replace(temp_path, destination)
    finally:
        for temp_path, _destination in temporaries:
            try:
                temp_path.unlink()
            except FileNotFoundError:
                pass


def emit_outputs(
    *,
    repo_root: Path,
    manifest_out: Path | None,
    markdown_out: Path | None,
) -> tuple[Path, Path]:
    manifest_bytes, markdown_bytes = build_output_bytes(repo_root=repo_root)
    canonical_manifest = repo_root / MANIFEST_REL
    canonical_markdown = repo_root / MARKDOWN_REL
    if manifest_out is None and markdown_out is None:
        if not _is_linked_detached_worktree(repo_root):
            raise PreservationValidationError(
                "canonical generation is allowed only in a detached linked C1 staged worktree"
            )
        manifest_path = assert_write_allowed(
            canonical_manifest, repo_root=repo_root, operation="generate portable manifest"
        )
        markdown_path = assert_write_allowed(
            canonical_markdown, repo_root=repo_root, operation="generate portable Markdown"
        )
    elif manifest_out is not None and markdown_out is not None:
        canonical = (canonical_manifest, canonical_markdown)
        manifest_path = assert_external_output(
            manifest_out,
            repo_root=repo_root,
            canonical_paths=canonical,
            operation="emit portable manifest",
        )
        markdown_path = assert_external_output(
            markdown_out,
            repo_root=repo_root,
            canonical_paths=canonical,
            operation="emit portable Markdown",
        )
        if manifest_path == markdown_path:
            raise PreservationValidationError("manifest and Markdown outputs must differ")
    else:
        raise PreservationValidationError(
            "--manifest-out and --markdown-out must be supplied together"
        )
    _atomic_materialize(
        ((manifest_path, manifest_bytes), (markdown_path, markdown_bytes))
    )
    return manifest_path, markdown_path


def check_outputs(*, repo_root: Path) -> None:
    expected_manifest, expected_markdown = build_output_bytes(repo_root=repo_root)
    for path, expected in (
        (repo_root / MANIFEST_REL, expected_manifest),
        (repo_root / MARKDOWN_REL, expected_markdown),
    ):
        try:
            actual = path.read_bytes()
        except OSError as exc:
            raise PreservationPrerequisiteError(
                f"canonical generated authority is unreadable: {path}: {exc}"
            ) from exc
        if actual != expected:
            raise PreservationValidationError(
                f"canonical generated authority differs from regeneration: {path}"
            )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest-out", type=Path)
    parser.add_argument("--markdown-out", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    if args.check and (args.manifest_out is not None or args.markdown_out is not None):
        parser.error("--check accepts no output options")

    try:
        repo_root = discover_repo_root(Path(__file__))
        if args.check:
            check_outputs(repo_root=repo_root)
            print("preserved_binaries: ok")
        else:
            manifest, markdown = emit_outputs(
                repo_root=repo_root,
                manifest_out=args.manifest_out,
                markdown_out=args.markdown_out,
            )
            print(f"preserved_binaries: wrote {manifest} and {markdown}")
    except PreservationPrerequisiteError as exc:
        print(f"preserved_binaries: prerequisite missing: {exc}", file=sys.stderr)
        return 2
    except (PreservationValidationError, ProtectedPathError) as exc:
        print(f"preserved_binaries: FAIL {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
